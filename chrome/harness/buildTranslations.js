/* Build harness/translations.js from the copied en-US .properties files.
 * Produces a single { token: string } map, matching what the Muon main
 * process used to return for ipcRenderer.sendSync('translations').
 *
 * Run once (and any time you refresh locales):
 *   node harness/buildTranslations.js
 */
const fs = require('fs')
const path = require('path')

const localeDir = path.resolve(__dirname, '..', 'app', 'extensions', 'brave', 'locales', 'en-US')
const out = {}

for (const file of fs.readdirSync(localeDir)) {
  if (!file.endsWith('.properties')) continue
  const text = fs.readFileSync(path.join(localeDir, file), 'utf8')
  for (const rawLine of text.split(/\r?\n/)) {
    const line = rawLine.trim()
    if (!line || line.startsWith('#') || line.startsWith('//')) continue
    const eq = line.indexOf('=')
    if (eq === -1) continue
    const key = line.slice(0, eq).trim()
    const value = line.slice(eq + 1).trim()
    if (key) out[key] = value
  }
}

const banner = '/* AUTO-GENERATED by harness/buildTranslations.js from en-US .properties.\n' +
  ' * Returned by the Muon shim for ipcRenderer.sendSync(\'translations\'). */\n'
fs.writeFileSync(
  path.resolve(__dirname, 'translations.js'),
  banner + 'module.exports = ' + JSON.stringify(out, null, 2) + '\n'
)
console.log('Wrote harness/translations.js with ' + Object.keys(out).length + ' tokens')
